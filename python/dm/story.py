def _check_look(look):
    # Either the base item's model recoloured towards a tint, or a model of the story's own (an OBJ file with its PNG
    # texture in dm_runtime/assets/models, see looks.py).
    if isinstance(look, dict) and "model" in look:
        from dm import looks
        if not looks.plain_name(look["model"], ".obj"):
            raise PlanError("define_item look model needs an .obj file name")
        texture = look.get("texture", "")
        if texture and not looks.plain_name(texture, ".png"):
            raise PlanError("define_item look texture needs a .png file name")
        scale = look.get("scale", 1)
        if isinstance(scale, bool) or not isinstance(scale, (int, float)) or not 0 < scale <= 1000:
            raise PlanError("define_item look scale needs a number above 0, up to 1000")
        for name in (look["model"], texture):
            if name and not (looks.models_dir() / name).is_file():
                raise PlanError(f"define_item look file not in dm_runtime/assets/models: {name}")
        return
    if not (isinstance(look, dict) and isinstance(look.get("tint"), list) and len(look["tint"]) == 3
            and all(isinstance(v, (int, float)) and 0 <= v <= 2 for v in look["tint"])):
        raise PlanError("define_item look needs a tint of three numbers from 0 to 2, or a model")


def _check_define_item(args, state):
    _require(args, "item", "like", "name", "carrier")
    if not isinstance(args["item"], str) or not args["item"].strip():
        raise PlanError("define_item needs an item id")
    if gothic.world.instance_kind(args["like"]) != "item":
        raise PlanError(f"not an item instance: {args['like']}")
    if not isinstance(args["name"], str) or not args["name"].strip():
        raise PlanError("define_item needs a name")
    look = args.get("look")
    if look is not None:
        _check_look(look)
    damage = args.get("damage", 0)
    if not isinstance(damage, int) or isinstance(damage, bool) or not 0 <= damage <= 10:
        raise PlanError("define_item damage is a whole number from 0 to 10, added to the base's")
    rows = args.get("rows", [])
    if not isinstance(rows, list) or len(rows) > 5 or not all(
            isinstance(r, list) and len(r) == 2 and isinstance(r[0], str) and isinstance(r[1], int) for r in rows):
        raise PlanError("define_item rows are up to five [label, number] pairs")


def _fold_define_item(args, state):
    state.setdefault("items", {})[args["item"].upper()] = {
        "carrier": args["carrier"], "like": args["like"], "name": args["name"],
        "description": args.get("description", ""), "rows": args.get("rows", []), "value": args.get("value", -1),
        "look": args.get("look"), "damage": args.get("damage", 0)}


def _define_in_world(entry):
    if not hasattr(gothic.world, "define_item"):
        return
    visual = ""
    look = entry.get("look")
    if look and "model" in look:
        from dm import looks
        try:
            visual = looks.model(gothic, look["model"], look.get("texture", ""), look.get("scale", 1))
        except (OSError, RuntimeError, ValueError):
            visual = ""             # no shape of its own, then: the base item's
    elif look and hasattr(gothic.world, "item_visual"):
        from dm import looks
        try:
            visual = looks.variant(gothic, gothic.world.item_visual(entry["like"]), look)
        except (OSError, RuntimeError, ValueError):
            visual = ""             # no look of its own, then: the base item's
    gothic.world.define_item(entry["carrier"], entry["like"], entry["name"], entry["description"],
                             [tuple(r) for r in entry["rows"]], entry["value"], visual, entry.get("damage", 0))


def _world_define_item(args):
    _define_in_world({"carrier": args["carrier"], "like": args["like"], "name": args["name"],
                      "description": args.get("description", ""), "rows": args.get("rows", []),
                      "value": args.get("value", -1), "look": args.get("look"), "damage": args.get("damage", 0)})
    return None


def _check_spawn(args, state):
    _require(args, "instance", "waypoint")
    _npc_instance(args["instance"])
    if gothic.world.find_npc(args["instance"]) is not None:
        raise PlanError(f"NPC already exists: {args['instance']}")
    if not gothic.world.has_waypoint(args["waypoint"]):
        raise PlanError(f"no such waypoint: {args['waypoint']}")
    state.setdefault("returning", []).append(args["instance"].upper())


def _world_spawn(args):
    npc = gothic.world.spawn(args["instance"], args["waypoint"])
    npc.stand_here()
    if "armor" in args:
        npc.wear(args["armor"])
    if "display_name" in args:
        npc.display_name = args["display_name"]
    return lambda: gothic.world.remove_npc(npc)


def _check_relocate(args, state):
    _require(args, "instance", "waypoint")
    name = _npc_instance(args["instance"])
    if name not in SAFE_TO_REMOVE:
        raise PlanError(f"NPC is not on the safe list: {name}")
    if not gothic.world.has_waypoint(args["waypoint"]):
        raise PlanError(f"no such waypoint: {args['waypoint']}")
    _live_npc(name)
    if "armor" in args and gothic.world.instance_kind(args["armor"]) != "item":
        raise PlanError(f"not an item instance: {args['armor']}")


def _world_relocate(args):
    gothic.world.remove_npc(_live_npc(args["instance"]))
    npc = gothic.world.spawn(args["instance"], args["waypoint"])
    npc.stand_here()
    if "armor" in args:
        npc.wear(args["armor"])
    if "display_name" in args:
        npc.display_name = args["display_name"]
    return None


