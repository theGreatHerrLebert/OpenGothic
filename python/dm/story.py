def _ready_live(args, plan):
    """Someone an effect moves, renames, removes or talks through must be in the world when the plan runs, unless the
    plan brings him."""
    name = str(args.get("instance") or args.get("npc") or "").upper()
    brought = {str(op.get("instance", "")).upper() for op in plan if op.get("op") in ("spawn_npc", "return_npc")}
    if name not in brought and gothic.world.find_npc(name) is None:
        raise NotReady(f"not in the world right now: {name}")


# Checked against the live game just before a plan runs, before any effect: what could make an effect fail although
# the plan is valid. Failing here changes nothing.
_READY = {"trip": _ready_trip, "send_npc": _ready_live, "relocate_npc": _ready_live, "remove_npc": _ready_live,
          "rename_npc": _ready_live, "attach_dialogue_graph": _ready_live}
# Effects that cannot be undone run after every effect that can, so a failure among the undoable ones still leaves
# the world untouched. Removal comes last of all.
_FINAL = {"give_xp", "journal", "trip", "send_npc", "relocate_npc"}
_LAST = {"remove_npc"}


def _phase(op):
    name = op["op"]
    return 0 if name == "define_item" else 3 if name in _LAST else 2 if name in _FINAL else 1


class Story:
    def __init__(self):
        self.state = empty_state()
        self.log = []
        self.queue = []
        self.results = []
        self.generation = None
        self.active_scene = None
        self.scene_opened = False
        self.scene_wait = 0
        self.topics_generation = None
        self.topics_shown = {}
        self.reserved = {}   # (scheme, x, z) of objects kept for the hero -> world generation it was set in
        self.evicted = {}    # the same key -> who had to make way, his routine held until it is given back

    def resolve_items(self, ops):
        """The plan with each item of the story's own (define_item) given its carrier, and every mention of the item's
        id (to place, give, take, check or notice it) put as that carrier: from here on it is an ordinary item."""
        known = {i: e["carrier"] for i, e in self.state.get("items", {}).items()}
        used = set(known.values())
        for op in ops:
            if isinstance(op, dict) and op.get("op") == "define_item" and isinstance(op.get("item"), str):
                item = op["item"].upper()
                if item not in known:
                    free = [c for c in ITEM_CARRIERS if c not in used]
                    if not free:
                        raise PlanError("no carrier left for another item of the story's own")
                    wanted = (op.get("carrier") or free[0]).upper()
                    if wanted not in free:   # only a free one of the pool: never a real item, never shared
                        raise PlanError(f"carrier not free: {wanted}")
                    known[item] = wanted
                    used.add(wanted)
                elif op.get("carrier") and op["carrier"].upper() != known[item]:
                    raise PlanError(f"{item} already has its carrier: {known[item]}")
        if not known:
            return ops

        def walk(value):
            # Only fields that name an item are put as the carrier ("instance" to place or give, "item" to check,
            # take, give or notice); a definition keeps its own fields, its name may well equal its id.
            if isinstance(value, list):
                return [walk(v) for v in value]
            if not isinstance(value, dict):
                return value
            if value.get("op") == "define_item":
                return dict(value, carrier=known[value["item"].upper()]) if isinstance(value.get("item"), str) else value
            out = {}
            for k, v in value.items():
                if k in ("instance", "item") and isinstance(v, str) and v.upper() in known:
                    out[k] = known[v.upper()]
                else:
                    out[k] = walk(v)
            return out
        return walk(ops)

    def validate(self, ops):
        """Raise PlanError unless the whole plan is acceptable."""
        if not ops:
            raise PlanError("empty plan")
        ops = self.resolve_items(ops)
        scratch = copy.deepcopy(self.state)
        for op in ops:
            name = op.get("op")
            if name not in OPS:
                raise PlanError(f"unknown operation: {name}")
            check, fold, _ = OPS[name]
            check(op, scratch)
            fold(op, scratch)

    def submit(self, reason, ops):
        """Validate now and queue for the next safe point."""
        self.validate(ops)
        self.queue.append({"reason": reason, "ops": ops})

    def apply_plan(self, plan):
        """All or nothing where the game allows it. Every effect that can fail for a reason the plan cannot see is
        checked first (NotReady, nothing happens). Undoable effects run first and are undone if any of them fails.
        Effects that cannot be undone (experience, journal, a trip, sending or removing someone) run last; if one of
        those fails, the log records exactly the part that happened and PartlyApplied is raised."""
        # State may have moved on since the plan was queued.
        plan = dict(plan, ops=creatures.assign_variants(self.resolve_items(plan["ops"]), self.state))
        # Readiness before validation: validation also finds someone missing, but as a broken plan, and a rule that
        # waits for him to come back must wait, not fail.
        for op in plan["ops"]:
            ready = _READY.get(op.get("op")) if isinstance(op, dict) else None
            if ready is not None:
                ready(op, plan["ops"])
        self.validate(plan["ops"])
        # Definitions first, so an item the plan gives or places is made as the story's own; then what can be undone,
        # then what cannot, removals last. The sort is stable, so the plan's own order holds within each phase.
        ordered = sorted(plan["ops"], key=_phase)
        undo, done, failed = [], [], None
        for op in ordered:
            effect = OPS[op["op"]][2]
            try:
                revert = effect(op) if effect is not None else None
            except Exception as err:
                failed = (op, err)
                break
            done.append(op)
            if revert is not None:
                undo.append(revert)
        if failed is not None:
            op, err = failed
            final_done = [o for o in done if _phase(o) >= 2]
            if not final_done:
                for revert in reversed(undo):
                    revert()
                raise err
            # The world has changed for good: keep the story in step with it. Everything but the failed effect and
            # the effects after it is recorded, so a load replays the same state the game now has.
            skipped = ordered[ordered.index(op):]
            kept = [o for o in plan["ops"] if not any(o is s for s in skipped)]
            self._record(plan["reason"] + " (teilweise)", kept)
            raise PartlyApplied(f"{op['op']} failed after effects that cannot be undone: {err}") from err
        self._record(plan["reason"], plan["ops"])

    def _record(self, reason, ops):
        hour, minute = gothic.world.time
        entry = {"seq": len(self.log) + 1, "day": gothic.world.day, "hour": hour,
                 "minute": minute, "reason": reason, "ops": ops}
        self.log.append(entry)
        self._fold(entry)

    def _fold(self, entry):
        for op in entry["ops"]:
            OPS[op["op"]][1](op, self.state)

    def player_flag(self, name, value=True):
        """Record a flag set by play, such as a dialogue node being reached."""
        hour, minute = gothic.world.time
        entry = {"seq": len(self.log) + 1, "day": gothic.world.day, "hour": hour,
                 "minute": minute, "reason": "player",
                 "ops": [{"op": "set_flag", "name": name, "value": value}]}
        self.log.append(entry)
        self._fold(entry)

    # ---- persistence ----

    def reset(self):
        _narration.clear()  # lines queued in another save's timeline must not play in this one
        self.__init__()

    def save(self, slot):
        SAVES_DIR.mkdir(parents=True, exist_ok=True)
        path = SAVES_DIR / f"{slot}.story.jsonl"
        tmp = path.with_suffix(".tmp")
        with tmp.open("w", encoding="utf-8") as f:
            for entry in self.log:
                f.write(json.dumps(entry, ensure_ascii=False) + "\n")
        os.replace(tmp, path)

    def load(self, slot):
        self.reset()
        path = SAVES_DIR / f"{slot}.story.jsonl"
        if not path.exists():
            return
        with path.open(encoding="utf-8") as f:
            for line in f:
                entry = json.loads(line)
                self.log.append(entry)
                self._fold(entry)

    # ---- game loop ----

    def rebind(self):
        """NPC handles do not survive a world load; attach graphs again, and define the story's own items again."""
        for entry in self.state.get("items", {}).values():
            _define_in_world(entry)
        creatures.rebind(self.state)
        for instance in self.state["graphs"]:
            npc = gothic.world.find_npc(instance)
            if npc is not None:
                gothic.dialog.bind(npc)

    def graphs_now(self):
        """Dialogue graphs, including the scene currently playing."""
        current = dict(self.state["graphs"])
        if self.active_scene is not None:
            scene = self.state["scenes"][self.active_scene[0]]
            current[scene["npc"]] = scene["graph"]
        return current

    def _conditions(self, entry):
        flags = self.state["flags"]
        required = entry.get("requires", entry.get("when", []))
        blocked = entry.get("unless") or []
        if isinstance(blocked, str):
            blocked = [blocked]
        return (all(flags.get(f) for f in required) and not any(flags.get(f) for f in blocked)
                and checks.all_hold(entry.get("checks")))

    def _guild_excluded(self, scene):
        guild = gothic.player.guild
        return any(gothic.daedalus.get(name, 0) == guild for name in scene.get("not_guilds", []))

    def _end_scene(self, finished):
        scene_id, npc = self.active_scene
        self.active_scene = None
        self.scene_opened = False
        gothic.dialog.unbind(npc)
        if finished:
            self.apply_plan({"reason": f"Szene beendet: {scene_id}",
                             "ops": [{"op": "finish_scene", "id": scene_id}]})

    def _tick_scenes(self):
        dialog = gothic.dialog
        if self.active_scene is not None:
            _, npc = self.active_scene
            if dialog.is_open():
                self.scene_opened = True
                return
            self.scene_wait += 1
            if self.scene_opened:
                self._end_scene(True)
            elif self.scene_wait > SCENE_OPEN_TICKS:
                self._end_scene(False)
            return
        if dialog.partner() is not None or gothic.player.busy:
            return
        px, _, pz = gothic.player.position
        for scene_id, scene in self.state.get("scenes", {}).items():
            if scene["done"] or ended(self.state, scene_id) or not self._conditions(scene):
                continue
            if self._guild_excluded(scene):
                continue
            npc = gothic.world.find_npc(scene["npc"])
            if npc is None or not npc.alive:
                continue
            x, _, z = npc.position
            if (px - x) ** 2 + (pz - z) ** 2 > scene["within"] ** 2:
                continue
            if not npc.can_see_player():
                continue
            dialog.bind(npc)
            npc.start_dialog()
            self.active_scene = (scene_id, npc)
            self.scene_opened = False
            self.scene_wait = 0
            return

    def _timing_allows(self, rule):
        if rule.get("after_night_of") is not None:
            # Sleeping skips the dark hours, so a passed day counts as a passed night.
            hour, _ = gothic.world.time
            if gothic.world.day <= rule["after_night_of"] and hour < 21:
                return False
        watched = rule.get("unseen_by_near")
        if watched:
            npc = gothic.world.find_npc(watched)
            if npc is not None:
                px, _, pz = gothic.player.position
                x, _, z = npc.position
                if (px - x) ** 2 + (pz - z) ** 2 < rule.get("unseen_range", UNSEEN_RANGE) ** 2:
                    return False
        return True

    def _weapon_events(self):
        """The game never raises its draw-weapon perception, so the hero's weapon state is polled instead."""
        drawn = getattr(gothic.player, "weapon", "none") != "none"
        was, self.weapon_drawn = getattr(self, "weapon_drawn", drawn), drawn
        if drawn and not was:
            seen = [n.instance for n in gothic.world.npcs_near(WITNESS_RANGE) if n.alive and n.can_see_player()]
            return [{"kind": "drew_weapon", "actor": perceptions.PLAYER, "target": "", "item": "", "spell": -1, "seen_by": seen}]
        return []

    def _tick_reservations(self):
        """An object a rule is waiting for the hero to use (a pipe filled for him) is kept for him while the rule's
        conditions hold: NPCs treat it as taken, and one sitting there gets up. Given back once the rule fired or
        its conditions lapse. The engine forgets reservations on a load; they are set again from here."""
        if not hasattr(gothic.world, "reserve_object"):
            return
        wanted = set()
        for rule in self.state.get("rules", {}).values():
            on = rule.get("on") or {}
            if on.get("event") == "used_object" and on.get("object") and len(on.get("near") or []) >= 2 \
                    and not rule["fired"] and self._conditions(rule):
                wanted.add((on["object"], float(on["near"][0]), float(on["near"][1])))
        generation = gothic.world.generation
        for key in list(self.reserved):
            if key not in wanted or self.reserved[key] != generation:
                self.evicted.pop(key, None)
                if self.reserved.pop(key) == generation:
                    gothic.world.reserve_object(*key, on=False)   # and whoever made way gets his routine back
        for key in wanted - set(self.reserved):
            evicted = gothic.world.reserve_object(*key, on=True)
            self.reserved[key] = generation
            if evicted:
                self.evicted[key] = evicted
                for hook in _hooks("made_way"):
                    hook(key, evicted)

    def _tick_topics(self):
        """Tells the engine which story topics each NPC's menu shows now; only what changed, and all again after a
        world change, when the engine has forgotten them."""
        if self.topics_generation != gothic.world.generation:
            self.topics_generation, self.topics_shown = gothic.world.generation, {}
        visible = {}
        for topic_id, topic in self.state.get("topics", {}).items():
            visible.setdefault(topic["npc"], [])
            if not ended(self.state, topic_id) and self._conditions(self._as_now(topic, topic_id)):
                visible[topic["npc"]].append((topic_id, topic["title"]))
        for hook in _hooks("extra_topics"):
            for instance, topics in hook(gothic).items():
                visible.setdefault(instance, []).extend(topics)   # an extension's topics beside the story's own
        for instance, topics in visible.items():
            npc = gothic.world.find_npc(instance)
            if npc is None:
                continue
            shown = (npc.id, topics)   # which NPC as well: one removed and spawned again needs them anew
            if self.topics_shown.get(instance) != shown:
                gothic.dialog.set_topics(npc, topics)
                self.topics_shown[instance] = shown

    def topic(self, key):
        """A topic's data if it may be played right now, or None: its conditions are checked again on choosing."""
        for extension in _extensions:
            prefix = getattr(extension, "TOPIC_PREFIX", None)
            if prefix and key.startswith(prefix):
                return extension.topic(key)
        topic = self.state.get("topics", {}).get(key)
        if topic is None or ended(self.state, key):
            return None
        return topic if self._conditions(self._as_now(topic, key)) else None

    def _as_now(self, topic, topic_id=None):
        """A topic's conditions as they stand now. Talking to its NPC puts him in the talk state, so what he was
        doing (smoking, drinking) is taken as it was the last time he was seen out of a conversation with the hero;
        everything else is asked now."""
        own = [c for c in topic.get("checks", []) if c.get("type") == "npc_state" and c.get("npc") == topic["npc"]]
        if not own:
            return topic
        partner = gothic.dialog.partner()
        held = getattr(self, "state_held", None)
        if held is None:
            held = self.state_held = {}
        key = topic_id or id(topic)
        if partner is None or partner.instance != topic["npc"]:
            held[key] = checks.all_hold(own)    # what he is doing now, remembered for when he talks
            return topic
        if not held.get(key, False):
            return topic                        # he was not doing it when the talk began: as it is now, not held
        return dict(topic, checks=[c for c in topic.get("checks", []) if c not in own])

    def _take_perceptions(self):
        """A rule hears only what happens while its own conditions hold, and hears it once."""
        for event in gothic.world.take_perceptions() + self._weapon_events():
            recent.append(event)
            for rule_id, rule in self.state.get("rules", {}).items():
                if (rule.get("on") and not rule["fired"] and not rule.get("perceived") and not ended(self.state, rule_id)
                        and self._conditions(rule)
                        and perceptions.matches(rule["on"], event)):
                    self.apply_plan({"reason": f"Wahrgenommen: {rule_id}", "ops": [{"op": "perceive", "id": rule_id}]})

    def _tick_rules(self):
        for rule_id, rule in self.state.get("rules", {}).items():
            if rule["fired"] or rule.get("failed") or ended(self.state, rule_id) or not self._conditions(rule):
                continue
            if rule.get("on") and not rule.get("perceived"):
                continue
            if not self._timing_allows(rule):
                continue
            plan = {"reason": f"Regel: {rule_id}",
                    "ops": rule["ops"] + [{"op": "fire_rule", "id": rule_id}]}
            try:
                self.apply_plan(plan)
                self.results.append({"reason": plan["reason"], "ok": True})
            except NotReady:
                continue   # tried again on a later tick
            except (PlanError, RuntimeError, ValueError) as err:
                self.results.append({"reason": plan["reason"], "ok": False, "error": str(err)})
                if not self.state["rules"][rule_id].get("fired"):
                    # Kept in the log, so a load does not try the broken rule again.
                    self._record(f"Regel gescheitert: {rule_id}",
                                 [{"op": "fail_rule", "id": rule_id, "error": str(err)[:200]}])

    def _tick_cast(self):
        """The safety net: a story whose cast member has died ends quietly, unless one of its closures speaks of that
        death (it fires as a rule of its own). A story that ends this way leaves nothing waiting in the world."""
        for story_id, story in self.state.get("stories", {}).items():
            if story["ended"] is not None:
                continue
            for instance in story.get("cast", []):
                if instance in self.state.get("removed", []):
                    continue   # taken out by a story on purpose
                npc = gothic.world.find_npc(instance)
                if npc is None or not npc.dead:
                    continue   # alive, or in another world
                own = [r for rid, r in self.state.get("rules", {}).items() if story_of(rid) == story_id]
                if any("npc_dead" in json.dumps(r.get("checks", [])) and instance in json.dumps(r.get("checks", [])).upper()
                       for r in own):
                    continue
                self._record(f"Geschichte endet: {instance} ist tot",
                             [{"op": "end_story", "story": story_id, "outcome": f"cast_dead:{instance}"}])
                self.results.append({"reason": f"{story['title']}: endet still", "ok": True})
                break

    def health(self):
        """What each story is doing, without giving anything away: started, ended and how, rules waiting or broken."""
        out = {}
        for story_id, story in self.state.get("stories", {}).items():
            rules = [r for rid, r in self.state.get("rules", {}).items() if story_of(rid) == story_id]
            started = story.get("started")
            out[story_id] = {"title": story["title"], "ended": story["ended"],
                             "days": None if started is None else gothic.world.day - started,
                             "rules_waiting": sum(1 for r in rules if not r["fired"] and not r.get("failed")),
                             "rules_fired": sum(1 for r in rules if r["fired"]),
                             "rules_failed": sum(1 for r in rules if r.get("failed"))}
        return out

    def _track_hero(self):
        for flag, guild in HERO_GUILD_FLAGS.items():
            if not self.state["flags"].get(flag) and gothic.player.guild == gothic.daedalus.get(guild, 0):
                self.player_flag(flag)

    def _tick_narration(self):
        if not _narration or gothic.dialog.partner() is not None or gothic.dialog.narrating():
            return
        now = time.monotonic()
        if now < getattr(self, "narrator_quiet_until", 0.0):
            return
        line = _narration[0]
        wav, ms = voices.lookup(line["voice"], line["text"])
        if gothic.dialog.narrate(line["text"], ms, wav):
            _narration.popleft()
            self.narrator_quiet_until = now + max(ms, 2500) / 1000 + NARRATOR_GAP_S

    def on_tick(self):
        generation = gothic.world.generation
        if generation != self.generation:
            self.generation = generation
            self.active_scene = None
            self.rebind()

        self._track_hero()
        self._take_perceptions()
        self._tick_topics()
        self._tick_reservations()
        self._tick_narration()

        self._tick_scenes()
        if gothic.dialog.partner() is None:
            self._tick_rules()
            self._tick_cast()

        if gothic.dialog.partner() is None and self.queue:
            plan = self.queue.pop(0)
            try:
                self.apply_plan(plan)
                self.results.append({"reason": plan["reason"], "ok": True})
            except NotReady:
                self.queue.append(plan)   # waits behind the rest, tried again on a later tick
            except (PlanError, RuntimeError, ValueError) as err:
                self.results.append({"reason": plan["reason"], "ok": False,
                                     "error": str(err)})


