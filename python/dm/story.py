def _tick(dt):
    try:
        gothic.world.day   # needs a world, unlike the generation counter
    except RuntimeError:
        return  # no active world while loading
    try:
        _story.on_tick()
        _player.on_tick()
    except Exception as err:
        # A bug, not a loading screen: say so once per kind of failure instead of hiding it, and keep ticking.
        key = f"{type(err).__name__}: {err}"
        if key not in _reported and len(_reported) < 50:
            _reported.add(key)
            import traceback
            traceback.print_exc()
            _story.results.append({"reason": "Spielleiter-Takt", "ok": False, "error": key[:300]})


def start():
    """Safe to call repeatedly."""
    if getattr(gothic, "_dm_story_registered", False):
        return
    module = "dm.story"
    gothic.on_tick(lambda dt: _module(module)._tick(dt))
    gothic._save_callbacks.append(lambda slot: _module(module)._story.save(slot))
    gothic._load_callbacks.append(lambda slot: _module(module)._story.load(slot))
    gothic._new_game_callbacks.append(lambda world: _module(module)._story.reset())
    gothic._dm_story_registered = True


def _module(name):
    import sys
    return sys.modules[name]


def submit(reason, ops):
    _story.submit(reason, ops)


def state():
    return _story.state


def results():
    return list(_story.results)
