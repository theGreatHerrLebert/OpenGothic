"""Typed story operations, all-or-nothing plans, and the persistent story log.

A plan is a list of operations. It is validated as a whole against a copy of the
story state, then applied at a safe point in the game loop. If anything fails,
nothing is kept.

The savegame already stores world changes, such as placed items and removed
NPCs. Loading therefore rebuilds only story state from the log and never
re-applies world effects.

    import dm.story as story
    story.start()
    story.submit("Der Novize verschwindet", [
        {"op": "commit_fact", "id": "culprit", "text": "...", "known_by": []},
        {"op": "do_nothing", "reason": "wait until nightfall"},
    ])
"""

import copy
import json
import os
import pathlib

import gothic

from dm import graph as graphs

RUNTIME_DIR = pathlib.Path(__file__).resolve().parent.parent / "dm_runtime"
SAVES_DIR = RUNTIME_DIR / "saves"

# NPCs the original scripts do not depend on, generated by depmap.py. An NPC
# outside this set cannot be removed by a story.
SCENE_RANGE = 450         # 100 units is about one metre
UNSEEN_RANGE = 900        # a change this close to the player could be seen
SCENE_OPEN_TICKS = 300    # give up on a scene that does not open, and retry later
SAFE_TO_REMOVE = set(json.loads((pathlib.Path(__file__).parent / "safe_npcs.json").read_text()))


class PlanError(Exception):
    pass


def empty_state():
    return {"facts": {}, "flags": {}, "removed": [], "graphs": {}, "scenes": {}, "rules": {}}


def _require(args, *keys):
    for key in keys:
        if key not in args:
            raise PlanError(f"missing field: {key}")


def _npc_instance(name):
    if gothic.world.instance_kind(name) != "npc":
        raise PlanError(f"not an NPC instance: {name}")
    return name.upper()


def _live_npc(name):
    npc = gothic.world.find_npc(name)
    if npc is None:
        raise PlanError(f"NPC is not in this world: {name}")
    return npc


# Each operation has:
#   check(args, state)  raises PlanError if the operation is not allowed
#   fold(args, state)   the pure change to story state
#   world(args)         optional side effect, returning an undo function or None

def _check_fact(args, state):
    _require(args, "id", "text")
    if args["id"] in state["facts"]:
        raise PlanError(f"fact already committed: {args['id']}")
    for name in args.get("known_by", []):
        _npc_instance(name)


def _fold_fact(args, state):
    state["facts"][args["id"]] = {
        "text": args["text"],
        "known_by": [n.upper() for n in args.get("known_by", [])],
    }


def _check_remove(args, state):
    _require(args, "instance")
    name = _npc_instance(args["instance"])
    if name not in SAFE_TO_REMOVE:
        raise PlanError(f"NPC is not on the safe list: {name}")
    if name in state["removed"]:
        raise PlanError(f"NPC already removed: {name}")
    _live_npc(name)


def _fold_remove(args, state):
    state["removed"].append(args["instance"].upper())


def _world_remove(args):
    gothic.world.remove_npc(_live_npc(args["instance"]))
    return None


def _check_return(args, state):
    _require(args, "instance", "position")
    name = _npc_instance(args["instance"])
    if name not in state["removed"]:
        raise PlanError(f"NPC was not removed by a story: {name}")
    if len(args["position"]) != 3:
        raise PlanError("position must be x, y, z")
    if "armor" in args and gothic.world.instance_kind(args["armor"]) != "item":
        raise PlanError(f"not an item instance: {args['armor']}")


def _fold_return(args, state):
    state["removed"].remove(args["instance"].upper())
    state.setdefault("returning", []).append(args["instance"].upper())


def _world_return(args):
    npc = gothic.world.spawn(args["instance"])
    npc.set_position(*args["position"])
    npc.stand_here()
    if "armor" in args:
        npc.wear(args["armor"])
    if "display_name" in args:
        npc.display_name = args["display_name"]
    return lambda: gothic.world.remove_npc(npc)


def _check_place(args, state):
    _require(args, "instance", "waypoint")
    if gothic.world.instance_kind(args["instance"]) != "item":
        raise PlanError(f"not an item instance: {args['instance']}")
    if not gothic.world.has_waypoint(args["waypoint"]):
        raise PlanError(f"no such waypoint: {args['waypoint']}")


def _world_place(args):
    item = gothic.world.place_item(args["instance"], args["waypoint"], args.get("count", 1), args.get("position"))
    quest = args.get("quest")
    if quest:
        # the first row sits directly under the title, so it stays blank
        item.make_quest(quest["description"], [""] + quest.get("lines", []))
    return item.remove


def _check_graph(args, state):
    _require(args, "npc", "graph")
    name = _npc_instance(args["npc"])
    if name in state["removed"]:
        raise PlanError(f"NPC has been removed: {name}")
    if name not in state.get("returning", []):
        _live_npc(name)
    problem = graphs.validate(args["graph"])
    if problem:
        raise PlanError(f"bad dialogue graph: {problem}")


def _fold_graph(args, state):
    state["graphs"][args["npc"].upper()] = args["graph"]


def _world_graph(args):
    npc = _live_npc(args["npc"])
    gothic.dialog.bind(npc)
    return lambda: gothic.dialog.unbind(npc)


def _check_scene(args, state):
    _require(args, "id", "npc", "graph")
    if args["id"] in state.setdefault("scenes", {}):
        raise PlanError(f"scene already exists: {args['id']}")
    _npc_instance(args["npc"])
    problem = graphs.validate(args["graph"])
    if problem:
        raise PlanError(f"bad dialogue graph: {problem}")


def _fold_scene(args, state):
    state.setdefault("scenes", {})[args["id"]] = {
        "npc": args["npc"].upper(), "graph": args["graph"], "within": args.get("within", SCENE_RANGE),
        "requires": args.get("requires", []), "unless": args.get("unless"), "done": False,
        "not_guilds": args.get("not_guilds", []),
    }


def _check_finish_scene(args, state):
    _require(args, "id")
    if args["id"] not in state.setdefault("scenes", {}):
        raise PlanError(f"no such scene: {args['id']}")


def _fold_finish_scene(args, state):
    state["scenes"][args["id"]]["done"] = True


def _check_rule(args, state):
    _require(args, "id", "when", "ops")
    if args["id"] in state.setdefault("rules", {}):
        raise PlanError(f"rule already exists: {args['id']}")
    for op in args["ops"]:
        if op.get("op") not in OPS:
            raise PlanError(f"unknown operation in rule: {op.get('op')}")


def _fold_rule(args, state):
    state.setdefault("rules", {})[args["id"]] = {
        "when": args["when"], "unless": args.get("unless"), "ops": args["ops"], "fired": False,
        "after_night_of": args.get("after_night_of"), "unseen_by_near": args.get("unseen_by_near"),
    }


def _check_fire_rule(args, state):
    _require(args, "id")
    if args["id"] not in state.setdefault("rules", {}):
        raise PlanError(f"no such rule: {args['id']}")


def _fold_fire_rule(args, state):
    state["rules"][args["id"]]["fired"] = True


def _check_give(args, state):
    _require(args, "instance")
    if gothic.world.instance_kind(args["instance"]) != "item":
        raise PlanError(f"not an item instance: {args['instance']}")


def _world_give(args):
    gothic.player.give_item(args["instance"], args.get("count", 1))
    return None


def _check_spawn(args, state):
    _require(args, "instance", "waypoint")
    _npc_instance(args["instance"])
    if gothic.world.find_npc(args["instance"]) is not None:
        raise PlanError(f"NPC already exists: {args['instance']}")
    if not gothic.world.has_waypoint(args["waypoint"]):
        raise PlanError(f"no such waypoint: {args['waypoint']}")
    state.setdefault("returning", []).append(args["instance"].upper())


def _world_spawn(args):
    npc = gothic.world.spawn(args["instance"], args["waypoint"])
    npc.stand_here()
    if "armor" in args:
        npc.wear(args["armor"])
    if "display_name" in args:
        npc.display_name = args["display_name"]
    return lambda: gothic.world.remove_npc(npc)


def _check_relocate(args, state):
    _require(args, "instance", "waypoint")
    name = _npc_instance(args["instance"])
    if name not in SAFE_TO_REMOVE:
        raise PlanError(f"NPC is not on the safe list: {name}")
    if not gothic.world.has_waypoint(args["waypoint"]):
        raise PlanError(f"no such waypoint: {args['waypoint']}")
    _live_npc(name)
    if "armor" in args and gothic.world.instance_kind(args["armor"]) != "item":
        raise PlanError(f"not an item instance: {args['armor']}")


def _world_relocate(args):
    gothic.world.remove_npc(_live_npc(args["instance"]))
    npc = gothic.world.spawn(args["instance"], args["waypoint"])
    npc.stand_here()
    if "armor" in args:
        npc.wear(args["armor"])
    if "display_name" in args:
        npc.display_name = args["display_name"]
    return None


def _check_rename(args, state):
    _require(args, "instance", "display_name")
    _npc_instance(args["instance"])
    _live_npc(args["instance"])


def _world_rename(args):
    npc = _live_npc(args["instance"])
    previous = npc.display_name
    npc.display_name = args["display_name"]
    return lambda: setattr(npc, "display_name", previous)


def _check_journal(args, state):
    _require(args, "topic")
    if "entry" not in args and "status" not in args:
        raise PlanError("journal needs an entry or a status")


def _world_journal(args):
    gothic.journal(args["topic"], args.get("entry", ""), args.get("status", 0))
    return None


def _check_detach(args, state):
    _require(args, "npc")


def _fold_detach(args, state):
    state["graphs"].pop(args["npc"].upper(), None)


def _world_detach(args):
    npc = gothic.world.find_npc(args["npc"])
    if npc is not None:
        gothic.dialog.unbind(npc)
    return None


def _check_flag(args, state):
    _require(args, "name", "value")


def _fold_flag(args, state):
    state["flags"][args["name"]] = args["value"]


def _check_nothing(args, state):
    _require(args, "reason")


def _noop(args, state):
    pass


OPS = {
    "commit_fact": (_check_fact, _fold_fact, None),
    "remove_npc": (_check_remove, _fold_remove, _world_remove),
    "return_npc": (_check_return, _fold_return, _world_return),
    "place_item": (_check_place, _noop, _world_place),
    "attach_dialogue_graph": (_check_graph, _fold_graph, _world_graph),
    "set_flag": (_check_flag, _fold_flag, None),
    "do_nothing": (_check_nothing, _noop, None),
    "add_scene": (_check_scene, _fold_scene, None),
    "finish_scene": (_check_finish_scene, _fold_finish_scene, None),
    "add_rule": (_check_rule, _fold_rule, None),
    "fire_rule": (_check_fire_rule, _fold_fire_rule, None),
    "spawn_npc": (_check_spawn, _noop, _world_spawn),
    "detach_dialogue_graph": (_check_detach, _fold_detach, _world_detach),
    "journal": (_check_journal, _noop, _world_journal),
    "rename_npc": (_check_rename, _noop, _world_rename),
    "give_item": (_check_give, _noop, _world_give),
    "relocate_npc": (_check_relocate, _noop, _world_relocate),
}

# Removal cannot be undone, so it runs after everything that can.
_LAST = {"remove_npc"}


class Story:
    def __init__(self):
        self.state = empty_state()
        self.log = []
        self.queue = []
        self.results = []
        self.generation = None
        self.active_scene = None
        self.scene_opened = False
        self.scene_wait = 0
        self.failed_rules = set()

    def validate(self, ops):
        """Raise PlanError unless the whole plan is acceptable."""
        if not ops:
            raise PlanError("empty plan")
        scratch = copy.deepcopy(self.state)
        for op in ops:
            name = op.get("op")
            if name not in OPS:
                raise PlanError(f"unknown operation: {name}")
            check, fold, _ = OPS[name]
            check(op, scratch)
            fold(op, scratch)

    def submit(self, reason, ops):
        """Validate now and queue for the next safe point."""
        self.validate(ops)
        self.queue.append({"reason": reason, "ops": ops})

    def apply_plan(self, plan):
        # State may have moved on since the plan was queued.
        self.validate(plan["ops"])
        ordered = sorted(plan["ops"], key=lambda op: op["op"] in _LAST)
        undo = []
        try:
            for op in ordered:
                effect = OPS[op["op"]][2]
                if effect is not None:
                    revert = effect(op)
                    if revert is not None:
                        undo.append(revert)
        except Exception:
            for revert in reversed(undo):
                revert()
            raise

        hour, minute = gothic.world.time
        entry = {"seq": len(self.log) + 1, "day": gothic.world.day, "hour": hour,
                 "minute": minute, "reason": plan["reason"], "ops": plan["ops"]}
        self.log.append(entry)
        self._fold(entry)

    def _fold(self, entry):
        for op in entry["ops"]:
            OPS[op["op"]][1](op, self.state)

    def player_flag(self, name, value=True):
        """Record a flag set by play, such as a dialogue node being reached."""
        hour, minute = gothic.world.time
        entry = {"seq": len(self.log) + 1, "day": gothic.world.day, "hour": hour,
                 "minute": minute, "reason": "player",
                 "ops": [{"op": "set_flag", "name": name, "value": value}]}
        self.log.append(entry)
        self._fold(entry)

    # ---- persistence ----

    def reset(self):
        self.__init__()

    def save(self, slot):
        SAVES_DIR.mkdir(parents=True, exist_ok=True)
        path = SAVES_DIR / f"{slot}.story.jsonl"
        tmp = path.with_suffix(".tmp")
        with tmp.open("w", encoding="utf-8") as f:
            for entry in self.log:
                f.write(json.dumps(entry, ensure_ascii=False) + "\n")
        os.replace(tmp, path)

    def load(self, slot):
        self.reset()
        path = SAVES_DIR / f"{slot}.story.jsonl"
        if not path.exists():
            return
        with path.open(encoding="utf-8") as f:
            for line in f:
                entry = json.loads(line)
                self.log.append(entry)
                self._fold(entry)

    # ---- game loop ----

    def rebind(self):
        """NPC handles do not survive a world load; attach graphs again."""
        for instance in self.state["graphs"]:
            npc = gothic.world.find_npc(instance)
            if npc is not None:
                gothic.dialog.bind(npc)

    def graphs_now(self):
        """Dialogue graphs, including the scene currently playing."""
        current = dict(self.state["graphs"])
        if self.active_scene is not None:
            scene = self.state["scenes"][self.active_scene[0]]
            current[scene["npc"]] = scene["graph"]
        return current

    def _conditions(self, entry):
        flags = self.state["flags"]
        required = entry.get("requires", entry.get("when", []))
        blocked = entry.get("unless") or []
        if isinstance(blocked, str):
            blocked = [blocked]
        return all(flags.get(f) for f in required) and not any(flags.get(f) for f in blocked)

    def _guild_excluded(self, scene):
        guild = gothic.player.guild
        return any(gothic.daedalus.get(name, 0) == guild for name in scene.get("not_guilds", []))

    def _end_scene(self, finished):
        scene_id, npc = self.active_scene
        self.active_scene = None
        self.scene_opened = False
        gothic.dialog.unbind(npc)
        if finished:
            self.apply_plan({"reason": f"Szene beendet: {scene_id}",
                             "ops": [{"op": "finish_scene", "id": scene_id}]})

    def _tick_scenes(self):
        dialog = gothic.dialog
        if self.active_scene is not None:
            _, npc = self.active_scene
            if dialog.is_open():
                self.scene_opened = True
                return
            self.scene_wait += 1
            if self.scene_opened:
                self._end_scene(True)
            elif self.scene_wait > SCENE_OPEN_TICKS:
                self._end_scene(False)
            return
        if dialog.partner() is not None or gothic.player.busy:
            return
        px, _, pz = gothic.player.position
        for scene_id, scene in self.state.get("scenes", {}).items():
            if scene["done"] or not self._conditions(scene):
                continue
            if self._guild_excluded(scene):
                continue
            npc = gothic.world.find_npc(scene["npc"])
            if npc is None or not npc.alive:
                continue
            x, _, z = npc.position
            if (px - x) ** 2 + (pz - z) ** 2 > scene["within"] ** 2:
                continue
            if not npc.can_see_player():
                continue
            dialog.bind(npc)
            npc.start_dialog()
            self.active_scene = (scene_id, npc)
            self.scene_opened = False
            self.scene_wait = 0
            return

    def _timing_allows(self, rule):
        if rule.get("after_night_of") is not None:
            # Sleeping skips the dark hours, so a passed day counts as a passed night.
            hour, _ = gothic.world.time
            if gothic.world.day <= rule["after_night_of"] and hour < 21:
                return False
        watched = rule.get("unseen_by_near")
        if watched:
            npc = gothic.world.find_npc(watched)
            if npc is not None:
                px, _, pz = gothic.player.position
                x, _, z = npc.position
                if (px - x) ** 2 + (pz - z) ** 2 < UNSEEN_RANGE ** 2:
                    return False
        return True

    def _tick_rules(self):
        for rule_id, rule in self.state.get("rules", {}).items():
            if rule["fired"] or rule_id in self.failed_rules or not self._conditions(rule):
                continue
            if not self._timing_allows(rule):
                continue
            plan = {"reason": f"Regel: {rule_id}",
                    "ops": rule["ops"] + [{"op": "fire_rule", "id": rule_id}]}
            try:
                self.apply_plan(plan)
                self.results.append({"reason": plan["reason"], "ok": True})
            except (PlanError, RuntimeError, ValueError) as err:
                self.failed_rules.add(rule_id)
                self.results.append({"reason": plan["reason"], "ok": False, "error": str(err)})

    def on_tick(self):
        generation = gothic.world.generation
        if generation != self.generation:
            self.generation = generation
            self.active_scene = None
            self.rebind()

        self._tick_scenes()
        if gothic.dialog.partner() is None:
            self._tick_rules()

        if gothic.dialog.partner() is None and self.queue:
            plan = self.queue.pop(0)
            try:
                self.apply_plan(plan)
                self.results.append({"reason": plan["reason"], "ok": True})
            except (PlanError, RuntimeError, ValueError) as err:
                self.results.append({"reason": plan["reason"], "ok": False,
                                     "error": str(err)})


_story = Story()
_player = graphs.Player(lambda: _story.graphs_now(),
                        lambda name: _story.player_flag(name),
                        lambda: _story.state["flags"])


def _tick(dt):
    try:
        _story.on_tick()
        _player.on_tick()
    except RuntimeError:
        pass  # no active world while loading


def start():
    """Safe to call repeatedly."""
    if getattr(gothic, "_dm_story_registered", False):
        return
    module = "dm.story"
    gothic.on_tick(lambda dt: _module(module)._tick(dt))
    gothic._save_callbacks.append(lambda slot: _module(module)._story.save(slot))
    gothic._load_callbacks.append(lambda slot: _module(module)._story.load(slot))
    gothic._new_game_callbacks.append(lambda world: _module(module)._story.reset())
    gothic._dm_story_registered = True


def _module(name):
    import sys
    return sys.modules[name]


def submit(reason, ops):
    _story.submit(reason, ops)


def state():
    return _story.state


def results():
    return list(_story.results)
